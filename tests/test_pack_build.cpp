TEST(pack_build_writes_and_reads_the_packs_index) {
    // index.txt: a line a picture - its name and its kind - so that a pack goes on with its kinds known.
    std::map<std::string, ai::Kind> kinds = {{"world/256x256/0123456789abcdef.webp", ai::Kind::Ground},
                                             {"sprites/64x128/fedcba9876543210.webp", ai::Kind::Sprites},
                                             {"ui/24x24/00000000000000aa.webp", ai::Kind::Icons}};
    const std::string text = pack::indexText(kinds);
    CHECK_EQ(text, std::string("sprites/64x128/fedcba9876543210.webp\tsprites\n"
                               "ui/24x24/00000000000000aa.webp\ticons\n"
                               "world/256x256/0123456789abcdef.webp\tground\n"));
    const auto back = pack::parseIndex(text + "broken line\nworld/32x32/1111111111111111.webp\tnonsense\n");
    CHECK_EQ(back.size(), size_t(4));
    CHECK(back.at("world/256x256/0123456789abcdef.webp") == ai::Kind::Ground);
    CHECK(back.at("ui/24x24/00000000000000aa.webp") == ai::Kind::Icons);
    CHECK(back.at("world/32x32/1111111111111111.webp") == ai::Kind::None);  // a kind it does not know
}

TEST(pack_build_finds_the_hair_palettes_of_a_head) {
    // 0.49: the game draws a head with the hair colour's palette (uaRO.exe: "머리\머리%s%s_%d.pal"), so its frames in
    // the sprite cache are not the head file's own: the builder makes them with every palette there is.
    const std::string human = "\xC0\xCE\xB0\xA3\xC1\xB7", head = "\xB8\xD3\xB8\xAE\xC5\xEB",
                      hair = "\xB8\xD3\xB8\xAE", male = "\xB3\xB2", female = "\xBF\xA9";
    const std::string sprite = "data\\sprite\\" + human + "\\" + head + "\\" + male + "\\12_" + male + ".spr";
    std::vector<std::string> names = {
        "data\\palette\\" + hair + "\\" + hair + "12_" + male + "_0.pal",
        "data\\palette\\" + hair + "\\" + hair + "12_" + male + "_7.pal",
        "data\\palette\\" + hair + "\\" + hair + "12_" + female + "_1.pal",  // the other sex
        "data\\palette\\" + hair + "\\" + hair + "1_" + male + "_2.pal",     // another style
        "data\\palette\\" + hair + "\\" + hair + "12_" + male + "_x.pal",    // no colour number
        sprite,
    };
    std::sort(names.begin(), names.end());
    const std::vector<std::string> p = pack::palettesOf(sprite, names);
    CHECK_EQ(p.size(), size_t(2));
    CHECK(p[0].find(hair + "12_" + male + "_0.pal") != std::string::npos);
    CHECK(p[1].find(hair + "12_" + male + "_7.pal") != std::string::npos);
    CHECK(pack::palettesOf("data\\sprite\\" + human + "\\" + head + "\\" + female + "\\3_" + female + ".spr", names)
              .empty());
    CHECK(pack::palettesOf("data\\sprite\\monster\\poring.spr", names).empty());
}

TEST(pack_build_takes_the_colours_the_server_lets_be_worn) {
    // 2.2.5: the client has 128 hair colours a style and up to 700 clothes colours a job; the server lets 0-20 (2.5.19:
    // its stylist's, npc/custom/dye.txt) and 0-77 be worn - the builder read and made the others for nothing (its
    // reading pass took long on the heads)
    const std::string human = "\xC0\xCE\xB0\xA3\xC1\xB7", head = "\xB8\xD3\xB8\xAE\xC5\xEB",
                      hair = "\xB8\xD3\xB8\xAE", body = "\xB8\xF6\xC5\xEB", clothes = "\xB8\xF6", male = "\xB3\xB2",
                      job = "\xB0\xCB\xBB\xE7";
    const std::string sprite = "data\\sprite\\" + human + "\\" + head + "\\" + male + "\\12_" + male + ".spr";
    const std::string dress = "data\\sprite\\" + human + "\\" + body + "\\" + male + "\\" + job + "_" + male + ".spr";
    std::vector<std::string> names = {sprite, dress};
    for (int c : {0, 8, 9, 20, 21, 127}) names.push_back("data\\palette\\" + hair + "\\" + hair + "12_" + male + "_" +
                                                std::to_string(c) + ".pal");
    for (int c : {1, 77, 78, 699})
        names.push_back("data\\palette\\" + clothes + "\\" + job + "_" + male + "_" + std::to_string(c) + ".pal");
    std::sort(names.begin(), names.end());
    const pack::Choice c;
    CHECK(c.maxHairColour == 20 && c.maxClothColour == 77);
    const std::vector<std::string> hairs = pack::palettesOf(sprite, names, false, c.maxHairColour, c.maxClothColour);
    CHECK_EQ(hairs.size(), size_t(4));  // 0, 8, 9, 20 - not 21 or 127
    CHECK(hairs.size() == 4 && hairs[0].find("_0.pal") != std::string::npos);
    CHECK(hairs.size() == 4 && hairs[1].find("_20.pal") != std::string::npos);
    CHECK(hairs.size() == 4 && hairs[3].find("_9.pal") != std::string::npos);
    CHECK_EQ(pack::palettesOf(dress, names, true, c.maxHairColour, c.maxClothColour).size(), size_t(2));
    CHECK_EQ(pack::palettesOf(sprite, names).size(), size_t(6));  // no limit asked: every colour there is
}

TEST(pack_build_finds_the_clothes_colours_of_a_body_when_asked) {
    // 0.56: a body is drawn with its clothes' dye ("몸\%s%s_%d.pal"): "<job>_<sex>_<n>.pal" - only with
    // Choice::bodyColours, since it makes 4 to 9 times the bodies' frames.
    const std::string human = "\xC0\xCE\xB0\xA3\xC1\xB7", body = "\xB8\xF6\xC5\xEB", clothes = "\xB8\xF6",
                      male = "\xB3\xB2", job = "\xB0\xCB\xBB\xE7";  // 몸통, 몸, 남, 검사 (swordman)
    const std::string sprite = "data\\sprite\\" + human + "\\" + body + "\\" + male + "\\" + job + "_" + male + ".spr";
    std::vector<std::string> names = {
        "data\\palette\\" + clothes + "\\" + job + "_" + male + "_1.pal",
        "data\\palette\\" + clothes + "\\" + job + "_" + male + "_2.pal",
        "data\\palette\\" + clothes + "\\" + job + "_" + male + "_x.pal",
        sprite,
    };
    std::sort(names.begin(), names.end());
    CHECK(pack::palettesOf(sprite, names).empty());  // not asked for
    CHECK_EQ(pack::palettesOf(sprite, names, true).size(), size_t(2));
    pack::Choice c = pack::parseChoice("players,bodycolours");
    CHECK(c.players && c.bodyColours && !c.monsters);
    CHECK_EQ(pack::choiceText(c), std::string("players,bodycolours"));
    CHECK(!pack::Choice().bodyColours);
}

