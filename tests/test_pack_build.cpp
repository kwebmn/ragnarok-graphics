TEST(pack_build_takes_the_games_jpg_pictures) {
    // The loading screens (the interface's folder): the game's texture is a power of two a side, the picture in its
    // top left corner - found by its likeness; the water (a map's texture): the picture is the texture.
    const std::string ui = "\xC0\xAF\xC0\xFA\xC0\xCE\xC5\xCD\xC6\xE4\xC0\xCC\xBD\xBA";
    pack::Choice c;
    c.minSide = 16;
    const pack::Source loading = pack::sourceOf("data\\texture\\" + ui + "\\loading01.jpg", c);
    CHECK(loading.type == pack::Source::Jpeg && loading.kind == ai::Kind::Icons);
    std::vector<pack::Picture> p = pack::picturesOf(loading, kLoadingJpg, sizeof kLoadingJpg, c);
    CHECK_EQ(p.size(), size_t(1));
    CHECK(p[0].group == pack::Group::Ui && p[0].width == 256 && p[0].height == 256);
    CHECK(p[0].contentWidth == 200 && p[0].contentHeight == 150);
    CHECK(p[0].argb[0] >> 24 == 255 && p[0].argb[size_t(255) * 256 + 255] == 0);  // outside the picture: nothing
    const pack::Source water = pack::sourceOf("data\\texture\\water\\water000.jpg", c);
    CHECK(water.type == pack::Source::Jpeg && water.kind == ai::Kind::Objects);
    p = pack::picturesOf(water, kWaterJpg, sizeof kWaterJpg, c);
    CHECK(p.size() == 1 && p[0].group == pack::Group::World && p[0].width == 32 && p[0].contentWidth == 32);
    c.world = false;
    CHECK(pack::sourceOf("data\\texture\\water\\water000.jpg", c).type == pack::Source::None);
}

