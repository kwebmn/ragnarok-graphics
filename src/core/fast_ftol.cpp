namespace uagfx::fastftol {

// push ebp; mov ebp, esp; add esp, -0xC; fstcw [ebp-2]; fwait; mov ax, [ebp-2]; or ah, 0xC; mov [ebp-4], ax;
// fldcw [ebp-4]; fistp qword [ebp-0xC]; fldcw [ebp-2]; mov eax, [ebp-0xC]; mov edx, [ebp-8]; leave; ret
const uint8_t kFtolBytes[kFtolSize] = {0x55, 0x8B, 0xEC, 0x83, 0xC4, 0xF4, 0x9B, 0xD9, 0x7D, 0xFE, 0x9B, 0x66, 0x8B,
                                       0x45, 0xFE, 0x80, 0xCC, 0x0C, 0x66, 0x89, 0x45, 0xFC, 0xD9, 0x6D, 0xFC, 0xDF,
                                       0x7D, 0xF4, 0xD9, 0x6D, 0xFE, 0x8B, 0x45, 0xF4, 0x8B, 0x55, 0xF8, 0xC9, 0xC3};

bool isFtolEntry(const uint8_t* bytes, size_t n) {
    return bytes && n == kFtolSize && std::memcmp(bytes, kFtolBytes, kFtolSize) == 0;
}

}  // namespace uagfx::fastftol
