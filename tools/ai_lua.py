import os
import sys


def main(folder):
    print("// Generated by tools/ai_lua.py from src/core/ai_lua - do not edit.")
    for name in ('AI.lua', 'AI_M.lua'):
        text = open(os.path.join(folder, name), encoding='utf-8').read()
        var = 'kAiLua' if name == 'AI.lua' else 'kAiMLua'
        print('constexpr const char* %s =\n    R"LUA(\n%s)LUA";' % (var, text))


if __name__ == '__main__':
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    main(sys.argv[1])
