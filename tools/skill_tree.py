#!/usr/bin/env python3
"""Writes src/core/skill_tree.inc (3.0.11-beta.96, «Навички»): the server's skill tree - each job's skills in the
server's order with their most levels and the skills (and levels) they need, its db/skill_tree.txt
(job, skill, max level, five pairs of a needed skill and its level).
Usage: python3 -I tools/skill_tree.py <uAthena>/db/skill_tree.txt > src/core/skill_tree.inc
"""
import sys


def tree(path):
    out = []
    for line in open(path, encoding='latin-1'):
        line = line.split('//')[0].strip()
        if not line:
            continue
        f = [v.strip() for v in line.split(',')]
        if len(f) < 13:
            continue
        try:
            v = [int(x) for x in f[:13]]
        except ValueError:
            continue
        job, sid, most = v[0], v[1], v[2]
        if not (0 <= job <= 65535 and 0 < sid <= 65535 and 0 < most <= 255):
            continue
        needs = [(v[3 + 2 * i], v[4 + 2 * i]) for i in range(5)]
        out.append((job, sid, most, needs))
    return out


def main(path):
    rows = tree(path)
    print('// Generated by tools/skill_tree.py from the server\'s db/skill_tree.txt - do not edit.')
    print('// {job, skill id, most levels, {needed skill, its level} x 5} in the server\'s order')
    print('constexpr Entry kTree[] = {')
    for job, sid, most, needs in rows:
        n = ', '.join('{%d, %d}' % p for p in needs)
        print('    {%d, %d, %d, {%s}},' % (job, sid, most, n))
    print('};')


if __name__ == '__main__':
    main(sys.argv[1])
