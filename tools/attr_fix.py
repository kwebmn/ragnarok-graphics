#!/usr/bin/env python3
"""Writes src/core/attr_fix.inc (3.0.11-beta.13): the server's element table - how much of an attack of each element a
monster of each element and level takes, in per cent (its db/attr_fix.txt, as pc_readdb reads it: a level's table, a
row an attack's element, a column the defence's; the server's battle_attr_fix takes [def_lv - 1][atk][def]). Below 0:
the attack heals (the server's attribute_recover: yes).
Usage: python3 -I tools/attr_fix.py <uAthena>/db/attr_fix.txt > src/core/attr_fix.inc
"""
import re
import sys


def table(path):
    out = [[[100] * 10 for _ in range(10)] for _ in range(4)]
    lv, rows, n = 0, 0, 0
    for line in open(path, encoding='latin-1'):
        line = line.split('//')[0].strip()
        if not line:
            continue
        head = re.fullmatch(r'(\d+)\s*,\s*(\d+)', line)
        if head:
            lv, n, rows = int(head.group(1)), int(head.group(2)), 0
            continue
        if lv < 1 or lv > 4 or rows >= min(n, 10):
            continue
        values = [int(v) for v in line.replace(',', ' ').split()]
        for j, v in enumerate(values[:10]):
            out[lv - 1][rows][j] = v
        rows += 1
    return out


def main(path):
    t = table(path)
    print('// Generated by tools/attr_fix.py from the server\'s db/attr_fix.txt - do not edit.')
    print('// [element level - 1][attack element][defence element], per cent')
    print('constexpr int kAttrFix[4][10][10] = {')
    for lv in range(4):
        print('    {')
        for a in range(10):
            print('        {' + ', '.join('%d' % v for v in t[lv][a]) + '},')
        print('    },')
    print('};')


if __name__ == '__main__':
    if len(sys.argv) != 2:
        print(__doc__)
        sys.exit(2)
    main(sys.argv[1])
