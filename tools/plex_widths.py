#!/usr/bin/env python3
"""Writes src/core/plex_widths.inc (3.0.11-beta.66): the advance widths of IBM Plex Sans Regular and SemiBold (the
new interface's words, third_party/plex) for the letters the interface writes - Latin, Latin-1, Cyrillic, the
punctuation, the arrows - in thousandths of the size, for core/window_panel's wordsWidth (the boxes made from it hold
the words GDI draws in that face: its widths at the sizes used are its linear ones).
Usage: python3 -I tools/plex_widths.py third_party/plex > src/core/plex_widths.inc
"""
import sys

from fontTools.ttLib import TTFont

RANGES = [(0x20, 0x7E), (0xA0, 0xFF), (0x400, 0x45F), (0x490, 0x491), (0x2010, 0x2027), (0x2030, 0x2030),
          (0x2039, 0x203A), (0x20B4, 0x20B4), (0x2116, 0x2116), (0x2190, 0x2193), (0x2212, 0x2212), (0x2713, 0x2713)]


def widths(path):
    font = TTFont(path)
    cmap = font.getBestCmap()
    hmtx = font['hmtx']
    scale = 1000.0 / font['head'].unitsPerEm
    return {c: int(round(hmtx[cmap[c]][0] * scale)) for lo, hi in RANGES for c in range(lo, hi + 1) if c in cmap}


def main(folder):
    regular = widths(folder + '/IBMPlexSans-Regular.ttf')
    semibold = widths(folder + '/IBMPlexSans-SemiBold.ttf')
    codes = sorted(set(regular) & set(semibold))
    print('// Generated by tools/plex_widths.py from third_party/plex - do not edit.')
    print('// {a letter, its advance in IBM Plex Sans Regular, in SemiBold} in thousandths of the size, by the letter')
    for c in codes:
        print('{0x%04X, %d, %d},' % (c, regular[c], semibold[c]))


if __name__ == '__main__':
    main(sys.argv[1])
