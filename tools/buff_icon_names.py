#!/usr/bin/env python3
"""Writes src/core/buff_icon_names.inc (3.0.11-beta.232, R-DS774A: «неопознаный эффект» - Auto Berserk's icon showed
«#132»): every status icon a skill gives - the server's status.c set_sc(skill, SC, SI, ...) lines, the SI's number from
status.h, the skill's name from skill_db.txt (its last column) - for the icons the durations table (core/buff_table)
has no name of (no time: Auto Berserk, the toggles).
Usage: python3 -I tools/buff_icon_names.py <uAthena> > src/core/buff_icon_names.inc
"""
import re
import sys


def main(root):
    si = {}
    for line in open(root + '/src/map/status.h', encoding='latin-1'):
        m = re.match(r'\s*(SI_[A-Z0-9_]+)\s*=\s*(\d+)', line)
        if m:
            si[m.group(1)] = int(m.group(2))
    names = {}
    for line in open(root + '/db/skill_db.txt', encoding='latin-1'):
        line = line.split('//')[0].strip()
        f = [v.strip() for v in line.split(',')]
        if len(f) > 16:
            names[f[15]] = ''.join(c for c in f[16] if 32 <= ord(c) < 127 and c not in '"\\')
    out = {}
    for line in open(root + '/src/map/status.c', encoding='latin-1'):
        m = re.search(r'set_sc\(\s*([A-Z0-9_]+)\s*,\s*SC_[A-Z0-9_]+\s*,\s*(SI_[A-Z0-9_]+)', line)
        if not m or m.group(2) not in si or m.group(1) not in names:
            continue
        out.setdefault(si[m.group(2)], names[m.group(1)])
    print('// Generated by tools/buff_icon_names.py from the server\'s status.c/.h and skill_db.txt - do not edit.')
    print('// {status icon, the name of the skill giving it}, by icon')
    print('constexpr IconName kIconNames[] = {')
    for icon in sorted(out):
        print('    {%d, "%s"},' % (icon, out[icon]))
    print('};')


if __name__ == '__main__':
    main(sys.argv[1])
