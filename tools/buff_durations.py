#!/usr/bin/env python3
"""buff_durations.py UATHENA OUT_CPP: the buff timers' table (3.0.4-beta.6) from the server's own data.

Which skill gives which status icon (src/map/status.c set_sc and StatusIconChangeTable, the icons' numbers in
src/map/status.h), how long by level (db/skill_cast_db.txt duration1, else duration2), and the items that give an icon
(db/item_db*.txt `sc_start SC_x,ms`, the longest time). Writes the C++ table core/buff_table.cpp reads.

Usage: python3 -I tools/buff_durations.py /root/uAthena src/core/buff_table_data.cpp
"""
import re
import sys
from pathlib import Path

MOST_MS = 24 * 3600 * 1000  # a day: longer ones are not buffs to count down


def icons(status_h):
    out = {}
    for name, value in re.findall(r"^\s*(SI_\w+)\s*=\s*(-?\d+)", status_h, re.M):
        out[name] = int(value)
    return out


def links(status_c):
    """(skill name, SC, SI) of set_sc and SC -> SI of the table's own lines, comments left out"""
    text = re.sub(r"//[^\n]*", "", status_c)
    text = re.sub(r"/\*.*?\*/", "", text, flags=re.S)
    by_skill = re.findall(r"set_sc\(\s*(\w+)\s*,\s*(SC_\w+)\s*,\s*(SI_\w+)", text)
    sc_si = {sc: si for _, sc, si in by_skill}
    for sc, si in re.findall(r"StatusIconChangeTable\[\s*(SC_\w+)\s*\]\s*=\s*(SI_\w+)", text):
        sc_si.setdefault(sc, si)
    return by_skill, sc_si


def skill_ids(skill_db):
    out = {}
    for line in skill_db.splitlines():
        if not line or line.startswith("//"):
            continue
        f = [x.strip() for x in line.split(",")]
        if len(f) > 3 and f[0].isdigit():
            out[f[-2]] = int(f[0])
    return out


def durations(cast_db):
    out = {}
    for line in cast_db.splitlines():
        line = line.split("//")[0].strip()
        if not line:
            continue
        f = [x.strip() for x in line.split(",")]
        if len(f) < 6 or not f[0].isdigit():
            continue
        def levels(x):
            try:
                return [int(v) for v in x.split(":")]
            except ValueError:
                return []
        one, two = levels(f[4]), levels(f[5])
        out[int(f[0])] = one if any(v > 0 for v in one) else two
    return out


def item_times(item_dbs):
    out = {}
    for text in item_dbs:
        for line in text.splitlines():
            if line.startswith("//"):
                continue
            for sc, ms in re.findall(r"(?<![\w_])sc_start\d?\s+(SC_\w+)\s*,\s*(\d+)", line):
                out[sc] = max(out.get(sc, 0), int(ms))
    return out


def main():
    root, out_path = Path(sys.argv[1]), Path(sys.argv[2])
    read = lambda p: (root / p).read_text(encoding="latin-1")
    si = icons(read("src/map/status.h"))
    by_skill, sc_si = links(read("src/map/status.c"))
    ids = skill_ids(read("db/skill_db.txt"))
    times = durations(read("db/skill_cast_db.txt"))
    items = item_times([read(p) for p in ("db/item_db.txt", "db/item_db2.txt") if (root / p).exists()])
    skills = []
    for skill, sc, icon in by_skill:
        if icon not in si or si[icon] < 0 or skill not in ids:
            continue
        ms = [v for v in times.get(ids[skill], []) if v > 0]
        if not ms or max(ms) > MOST_MS:
            continue
        ms = (ms + [ms[-1]] * 10)[:10]
        skills.append((si[icon], ids[skill], ms, skill))
    things = {}
    for sc, ms in items.items():
        icon = sc_si.get(sc)
        if icon in si and si[icon] >= 0 and 0 < ms <= MOST_MS:
            things[si[icon]] = max(things.get(si[icon], 0), ms)
    lines = ["// Generated by tools/buff_durations.py from the server's data (uAthena: status.c/.h, skill_db, "
             "skill_cast_db,", "// item_db) - not edited by hand.", '#include "core/buff_table.hpp"', "",
             "namespace uagfx::buffs {", "", "const SkillBuff kSkillBuffs[] = {"]
    for icon, skill, ms, name in sorted(skills):
        lines.append("    // " + name)
        lines.append("    {%d, %d, {%s}}," % (icon, skill, ", ".join(str(v) for v in ms)))
    lines += ["};", "const size_t kSkillBuffCount = sizeof kSkillBuffs / sizeof kSkillBuffs[0];", "",
              "const ItemBuff kItemBuffs[] = {"]
    for icon, ms in sorted(things.items()):
        lines.append("    {%d, %d}," % (icon, ms))
    lines += ["};", "const size_t kItemBuffCount = sizeof kItemBuffs / sizeof kItemBuffs[0];", "",
              "}  // namespace uagfx::buffs", ""]
    out_path.write_text("\n".join(lines), encoding="utf-8")
    print("skills %d, items %d -> %s" % (len(skills), len(things), out_path))


if __name__ == "__main__":
    main()
