#!/usr/bin/env python3
"""Writes src/core/skill_costs.inc (3.0.11-beta.45): the server's SP price of each skill by its level - its
db/skill_require_db.txt, the SPCost column (the fourth), as skill_split_atoi reads it: a level's value after each ':',
the levels past the last given the last's (no skill there gives fewer values than its levels and more than one).
Usage: python3 -I tools/skill_costs.py <uAthena>/db/skill_require_db.txt > src/core/skill_costs.inc
"""
import sys

MOST = 10


def costs(path):
    out = {}
    for line in open(path, encoding='latin-1'):
        line = line.split('//')[0].strip()
        if not line:
            continue
        fields = line.split(',')
        if len(fields) < 4:
            continue
        sp = [int(v) for v in fields[3].split(':') if v.strip()]
        if not sp or len(sp) > MOST or any(v < 0 or v > 65535 for v in sp):
            continue
        out[int(fields[0])] = sp
    return out


def main(path):
    t = costs(path)
    print('// Generated by tools/skill_costs.py from the server\'s db/skill_require_db.txt - do not edit.')
    print('// {skill id, levels given, SP by level} - the levels past those given cost the last given')
    print('constexpr SkillCost kSkillCosts[] = {')
    for sid in sorted(t):
        sp = t[sid]
        print('    {%d, %d, {%s}},' % (sid, len(sp), ', '.join('%d' % v for v in sp)))
    print('};')


if __name__ == '__main__':
    main(sys.argv[1])
