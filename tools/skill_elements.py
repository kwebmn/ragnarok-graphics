#!/usr/bin/env python3
"""Writes src/core/skill_elements.inc (3.0.11-beta.68): the element of each damaging skill with an element of its own,
by the server's db/skill_db.txt - its fifth column (0 neutral ... 9 undead; -1 the weapon's, -2/-3 the endowment's or
a random one: left out), the first level's when it differs by level; the skills with no damage (nk 0x01) or ignoring
the elements (nk 0x10) left out. The concept's «Ваша панель: Fire Bolt ×2…».
Usage: python3 -I tools/skill_elements.py <uAthena>/db/skill_db.txt > src/core/skill_elements.inc
"""
import sys


def elements(path):
    out = {}
    for line in open(path, encoding='latin-1'):
        line = line.split('//')[0].strip()
        if not line:
            continue
        f = [x.strip() for x in line.split(',')]
        if len(f) < 16:
            continue
        try:
            element = int(f[4].split(':')[0])
            nk = int(f[5], 0)
        except ValueError:
            continue
        name = f[15]
        if element < 0 or element > 9 or nk & 0x01 or nk & 0x10 or not name:
            continue
        out[name] = element
    return out


def main(path):
    t = elements(path)
    print("// Generated by tools/skill_elements.py from the server's db/skill_db.txt - do not edit.")
    print('// {a damaging skill\'s name, its element (0 neutral, 1 water, 2 earth, 3 fire, 4 wind, 5 poison, 6 holy, 7 dark,')
    print('// 8 ghost, 9 undead)}, by the name')
    for name in sorted(t):
        print('{"%s", %d},' % (name, t[name]))


if __name__ == '__main__':
    main(sys.argv[1])
