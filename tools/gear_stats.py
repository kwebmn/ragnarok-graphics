#!/usr/bin/env python3
"""gear_stats.py <uAthena>/db/item_db.txt <uAthena>/db/item_db2.txt > src/core/gear_stats.inc

3.0.11-beta.285 (the owner's feature 13, the gear compared in «Речі»'s tip): each weapon's and armour's numbers as
the server has them (db/item_db.txt, then db/item_db2.txt over it): ID,AegisName,Name,Type,Buy,Sell,Weight,ATK,DEF,
Range,Slots,Job,Upper,Gender,Loc,wLV,eLV,Refineable,View,{Script},...
"""
import sys


def num(x):
    x = x.strip()
    try:
        return int(x, 0)
    except ValueError:
        return 0


def main(paths):
    gear = {}
    for path in paths:
        for line in open(path, encoding='latin-1'):
            line = line.strip()
            if not line or line.startswith('//'):
                continue
            f = line.split(',')
            if len(f) < 19 or not f[0].strip().isdigit():
                continue
            kind = num(f[3])
            if kind not in (4, 5):
                gear.pop(num(f[0]), None)
                continue
            gear[num(f[0])] = (num(f[0]), kind, num(f[7]), num(f[8]), num(f[10]), num(f[14]), num(f[15]), num(f[16]))
    print("// Generated by tools/gear_stats.py from the server's db/item_db.txt and db/item_db2.txt - do not edit.")
    print('// {id, type (4 a weapon, 5 an armour), ATK, DEF, slots, where worn, weapon level, level needed}')
    print('constexpr Gear kGear[] = {')
    for k in sorted(gear):
        print('    {%s},' % ', '.join(str(v) for v in gear[k]))
    print('};')


if __name__ == '__main__':
    if len(sys.argv) < 2:
        sys.exit(__doc__)
    main(sys.argv[1:])
