#!/usr/bin/env python3
"""Writes src/core/mob_pictures.inc (3.0.19-beta.1): pictures of the monsters the clients have no sprite for
(tools/mob_pictures_ids.txt - players' logs «reference: no sprite for» on 3.0.18: Chonchon, Steel Chonchon, Verit,
Atroce, Beelzebub, Satan Morroc, the guardians, the treasure chests...) - the first frame of the site's
web/assets/mobs/<id>.gif, as «Довідник» and the target card show a monster when its sprite is not found.
A picture once however many monsters share it (40 treasure chests one), each packed: zlib of
[u16 width][u16 height][u16 colours][colours x u32 ARGB][width x height u8 colour numbers].
Usage: python3 -I tools/mob_pictures.py tools/mob_pictures_ids.txt /var/www/uaro.kiev.ua/web/assets/mobs
       > src/core/mob_pictures.inc
"""
import os
import struct
import sys
import zlib

from PIL import Image


def first_frame(path):
    im = Image.open(path)
    im.seek(0)
    rgba = im.convert('RGBA')
    colours, index, px = [], {}, []
    data = rgba.tobytes()
    for at in range(0, len(data), 4):
        r, g, b, a = data[at], data[at + 1], data[at + 2], data[at + 3]
        c = 0 if a < 128 else (0xFF000000 | r << 16 | g << 8 | b)
        if c not in index:
            if len(colours) == 256:  # past a palette's room: the nearest kept colour
                c = min(colours, key=lambda k: sum(abs(((k >> s) & 255) - ((c >> s) & 255)) for s in (0, 8, 16, 24)))
            else:
                index[c] = len(colours)
                colours.append(c)
        px.append(index[c])
    w, h = rgba.size
    raw = struct.pack('<HHH', w, h, len(colours)) + b''.join(struct.pack('<I', c) for c in colours) + bytes(px)
    return zlib.compress(raw, 9)


def main(ids_path, gifs):
    ids = []
    for line in open(ids_path, encoding='utf-8'):
        line = line.strip()
        if line and not line.startswith('#'):
            ids.append(int(line.split()[0]))
    blobs, of = [], []
    for i in sorted(set(ids)):
        path = os.path.join(gifs, '%d.gif' % i)
        if not os.path.exists(path):
            sys.stderr.write('no picture for %d\n' % i)
            continue
        blob = first_frame(path)
        if blob not in blobs:
            blobs.append(blob)
        of.append((i, blobs.index(blob)))
    out = ['// Generated by tools/mob_pictures.py from tools/mob_pictures_ids.txt and the site\'s monster pictures - do not',
           '// edit. %d monsters, %d pictures, %d bytes packed' % (len(of), len(blobs), sum(len(b) for b in blobs))]
    for n, blob in enumerate(blobs):
        out.append('constexpr unsigned char kMobPicture%d[] = {' % n)
        for at in range(0, len(blob), 20):
            out.append('    ' + ', '.join('%d' % b for b in blob[at:at + 20]) + ',')
        out.append('};')
    out.append('constexpr MobPictureBlob kMobPictureBlobs[] = {')
    for n, blob in enumerate(blobs):
        out.append('    {kMobPicture%d, %d},' % (n, len(blob)))
    out.append('};')
    out.append('constexpr MobPictureOf kMobPictureOf[] = {  // by the monster\'s number')
    for i, n in of:
        out.append('    {%d, %d},' % (i, n))
    out.append('};')
    print('\n'.join(out))


if __name__ == '__main__':
    main(sys.argv[1], sys.argv[2])
