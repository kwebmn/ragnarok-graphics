#!/usr/bin/env python3
"""skill_delay.py <uAthena>/db/skill_cast_db.txt > src/core/skill_delay.inc

3.0.11-beta.276 (the owner's feature 7: the delay after a skill on the hotbar): each skill's AfterCastActDelay by its
level (the server's db/skill_cast_db.txt: SkillID,CastingTime,AfterCastActDelay,...; a value «a:b:c» per level, the
last one for the levels past it). Only skills with a delay.
"""
import sys


def levels(v):
    parts = [int(x) for x in v.split(':') if x.strip() != '']
    return (parts + [parts[-1]] * 10)[:10] if parts else [0] * 10


def main(path):
    rows = {}
    for line in open(path, encoding='latin-1'):
        line = line.split('//')[0].strip()
        if not line:
            continue
        f = [x.strip() for x in line.split(',')]
        if len(f) < 3:
            continue
        try:
            sid = int(f[0])
            delay = levels(f[2])
        except ValueError:
            continue
        if any(delay) and sid not in rows:
            rows[sid] = delay
    print('// Generated by tools/skill_delay.py from the server\'s db/skill_cast_db.txt - do not edit.')
    print('// {skill, its AfterCastActDelay ms at levels 1-10}')
    print('constexpr Delay kDelays[] = {')
    for sid in sorted(rows):
        print('    {%d, {%s}},' % (sid, ', '.join(str(x) for x in rows[sid])))
    print('};')


if __name__ == '__main__':
    if len(sys.argv) != 2:
        raise SystemExit(__doc__)
    main(sys.argv[1])
