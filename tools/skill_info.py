#!/usr/bin/env python3
"""Writes src/core/skill_info.inc (3.0.11-beta.223, «Навички»: the skills the server has not sent): what each skill of
the server's tree is used on and how it is learned - its db/skill_db.txt, the inf column (the fourth: 0 passive, 1 an
enemy, 2 the ground, 4 itself, 16 a friend, 32 a trap) and the inf2 column (the twelfth: 0x01 a quest skill, 0x04 a
wedding skill, 0x08 a Soul Link one - pc_calc_skilltree never sends those by their requirements). Only the skills of
db/skill_tree.txt. 3.0.11-beta.228: its name too (the last column, English) - the client's table has none for some
(«Skill not defined !!»). 3.0.18-beta.244 («Довідник» › «Навички»): its AEGIS name (col 15), most level (7), element
(4, the first level's; -1 the weapon's) and kind (13).
Usage: python3 -I tools/skill_info.py <uAthena>/db/skill_db.txt <uAthena>/db/skill_tree.txt > src/core/skill_info.inc
"""
import sys


def rows(path):
    for line in open(path, encoding='latin-1'):
        line = line.split('//')[0].strip()
        if line:
            yield [v.strip() for v in line.split(',')]


def main(db, tree):
    wanted = set()
    for f in rows(tree):
        try:
            wanted.add(int(f[1]))
        except (ValueError, IndexError):
            pass
    out = []
    for f in rows(db):
        try:
            sid, inf, inf2 = int(f[0]), int(f[3], 0), int(f[11], 0)
            name = f[16] if len(f) > 16 else ''
            aegis = f[15] if len(f) > 15 else ''
            most = int(f[7]) if len(f) > 7 else 0
            element = int(f[4].split(':')[0]) if len(f) > 4 else 0
            kind = f[13] if len(f) > 13 else ''
        except (ValueError, IndexError):
            continue
        if sid in wanted:
            clean = lambda s: ''.join(c for c in s if 32 <= ord(c) < 127 and c not in '"\\')
            out.append((sid, inf & 0xFF, inf2 & 0x0D, clean(name), clean(aegis), most, element, clean(kind)))
    out.sort()
    print('// Generated by tools/skill_info.py from the server\'s db/skill_db.txt - do not edit.')
    print('// {skill id, used on (inf), how learned (inf2: 1 quest, 4 wedding, 8 Soul Link), name, AEGIS name,')
    print('// most level, element (its first level\'s; -1 the weapon\'s), kind (weapon / magic / misc / none)}')
    print('// - the tree\'s skills')
    print('constexpr Info kInfo[] = {')
    for sid, inf, inf2, name, aegis, most, element, kind in out:
        print('    {%d, %d, %d, "%s", "%s", %d, %d, "%s"},' % (sid, inf, inf2, name, aegis, most, element, kind))
    print('};')


if __name__ == '__main__':
    main(sys.argv[1], sys.argv[2])
