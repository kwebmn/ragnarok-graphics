#!/usr/bin/env python3
"""job_info.py <uAthena>/db > src/core/job_info.inc

3.0.11-beta.264 (the «Характеристики» concept, stage 1): the server's per-class numbers for the stats' formulas -
db/job_db1.txt (the most weight in tenths, HPFactor, HPMultiplicator, SPFactor, the attack delay of each of the 23
weapon types; 2000 = the class cannot use it), db/job_db2.txt (the stat a job level gives: 1 STR .. 6 LUK, 0 none) and
db/statpoint.txt (the stat points a base level has in all).
"""
import sys
from pathlib import Path


def rows(path):
    for line in Path(path).read_text(encoding='latin-1').splitlines():
        line = line.split('//')[0].strip()
        if line:
            yield [f.strip() for f in line.split(',')]


def main(db):
    db = Path(db)
    jobs = {}
    for f in rows(db / 'job_db1.txt'):
        if len(f) < 28 or int(f[0]) in jobs:
            continue
        jobs[int(f[0])] = [int(x) for x in f[1:28]]
    bonus = {}
    for f in rows(db / 'job_db2.txt'):
        if int(f[0]) not in bonus:
            bonus[int(f[0])] = ''.join(str(int(x)) for x in f[1:] if x != '')
    points = [int(f[0]) for f in rows(db / 'statpoint.txt')]
    print('// Generated by tools/job_info.py from the server\'s db/job_db1.txt, job_db2.txt, statpoint.txt - do not edit.')
    print('// {job, weight (tenths), HPFactor, HPMultiplicator, SPFactor, {the 23 weapons\' attack delays}, job bonuses}')
    print('constexpr Job kJobs[] = {')
    for j in sorted(jobs):
        v = jobs[j]
        print('    {%d, %d, %d, %d, %d,' % (j, v[0], v[1], v[2], v[3]))
        print('     {%s,' % ', '.join(str(x) for x in v[4:16]))
        print('      %s},' % ', '.join(str(x) for x in v[16:27]))
        print('     "%s"},' % bonus.get(j, ''))
    print('};')
    print('constexpr int kStatPoints[] = {')
    for i in range(0, len(points), 12):
        print('    ' + ', '.join(str(x) for x in points[i:i + 12]) + ',')
    print('};')


if __name__ == '__main__':
    if len(sys.argv) != 2:
        raise SystemExit(__doc__)
    main(sys.argv[1])
