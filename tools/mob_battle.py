#!/usr/bin/env python3
"""mob_battle.py <uAthena>/db/mob_db.txt <uAthena>/db/mob_db2.txt > src/core/mob_battle.inc

3.0.11-beta.279 (the owner's feature 5, the monster's card under the cursor): each monster's battle numbers as the
server has them (db/mob_db.txt, then db/mob_db2.txt over it - the server reads them in this order): ID,Sprite,kROName,
iROName,LV,HP,SP,EXP,JEXP,Range1,ATK1,ATK2,DEF,MDEF,STR,AGI,VIT,INT,DEX,LUK,Range2,Range3,Scale,Race,Element,Mode,
Speed,aDelay,...
"""
import sys


def main(paths):
    mobs = {}
    for path in paths:
        for line in open(path, encoding='latin-1'):
            line = line.split('//')[0].strip()
            if not line:
                continue
            f = [x.strip() for x in line.split(',')]
            if len(f) < 28 or not f[0].isdigit():
                continue
            n = [int(x, 0) if x.lstrip('-').isdigit() or x.startswith('0x') else 0 for x in f[:28]]
            # 3.0.16-beta.32: its size (Scale: 0 small, 1 medium, 2 large) and element (type + level * 20)
            mobs[n[0]] = (n[0], n[4], n[10], n[11], n[12], n[13], n[15], n[16], n[18], n[27], n[22], n[24])
    print("// Generated by tools/mob_battle.py from the server's db/mob_db.txt and db/mob_db2.txt - do not edit.")
    print('// {id, level, ATK1, ATK2, DEF, MDEF, AGI, VIT, DEX, aDelay ms, size, element}')
    print('constexpr Mob kMobs[] = {')
    for k in sorted(mobs):
        print('    {%s},' % ', '.join(str(v) for v in mobs[k]))
    print('};')


if __name__ == '__main__':
    if len(sys.argv) < 2:
        sys.exit(__doc__)
    main(sys.argv[1:])
